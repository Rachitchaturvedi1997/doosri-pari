# =============================================================================
# Write docs/API.md from the live OpenAPI document.
#
#     python -m python.tools.gen_api_doc
#
# The clients (Kotlin core-network, Swift services) are written against this. It
# is generated rather than hand-kept so it cannot drift from the routes: run it
# after any change to a router and commit the result.
# =============================================================================
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

TAB_ORDER = [
    ("auth", "Sign-in and identity"), ("setup", "Family-assisted setup"), ("me", "Profile, devices, verification"),
    ("prefs", "Settings, consents, inbox, cities"), ("today", "Today (Aaj)"), ("checkin", "Daily check-in"),
    ("safety", "SOS, guardians, scam shield"), ("ivr", "IVR webhooks (called by the telephony vendor)"),
    ("bolo", "Bolo voice router and search"), ("circles", "Saathi: circles, feed, events, connections, chat"),
    ("rooms", "Chai pe Charcha: voice rooms"), ("seva", "Seva: the Anubhav board"),
    ("payments", "Seva: payments and payouts"), ("sahayak", "Pension Sahayak"), ("toolkit", "Pension toolkit"),
    ("grievance", "Grievance helper"), ("vault", "Document safe (server side)"), ("health", "Health"),
    ("kendra", "Yog Kendra and Adhyatm Kendra"), ("content", "Content, news, radio, app config"),
    ("stories", "Meri Kahani"), ("seekho", "Seekho (learn)"), ("yatra", "Teerth yatra planner"),
    ("association", "Association workspace"), ("media", "Uploads and media"),
    ("subscriptions", "Family plan billing"), ("admin", "Admin console and volunteer desk"),
    ("realtime", "Realtime WebSocket"),
]


def main() -> None:
    from python.main import app

    spec = app.openapi()
    by_tag: dict[str, list[tuple[str, str, str, bool]]] = defaultdict(list)
    for path, ops in sorted(spec["paths"].items()):
        for method, op in ops.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            tag = (op.get("tags") or ["other"])[0]
            summary = (op.get("summary") or "").strip()
            doc = (op.get("description") or "").strip().split("\n\n")[0].replace("\n", " ")
            needs_auth = any(k in op for k in ("security",)) or "Authorization" in str(op.get("parameters", ""))
            by_tag[tag].append((method.upper(), path, doc or summary, needs_auth))

    total = sum(len(v) for v in by_tag.values())
    lines = [
        "# Doosri Pari API",
        "",
        f"Generated by `python -m python.tools.gen_api_doc`. **{total} operations.** "
        "Do not edit by hand.",
        "",
        "- REST + JSON. Auth is `Authorization: Bearer <access token>` from `/auth/verify`, "
        "`/auth/google` or `/auth/apple`; refresh with `/auth/refresh`.",
        "- Times are epoch seconds (float). Money is integer paise.",
        "- Errors are always `{\"detail\": \"...\", \"errors\": [{\"field\", \"msg\"}]}`.",
        "- Every response has `X-Request-ID`; quote it when reporting a problem.",
        "- Nothing personal is cacheable: responses carry `Cache-Control: no-store` except `/app/config` and media links.",
        "- Live updates: connect a WebSocket to `/ws?token=<access token>`; events are hints, "
        "REST is the source of truth.",
        "",
    ]
    seen = set()
    for tag, title in TAB_ORDER + [(t, t.title()) for t in sorted(by_tag) if t not in dict(TAB_ORDER)]:
        if tag in seen or tag not in by_tag:
            continue
        seen.add(tag)
        lines += [f"## {title}", ""]
        for method, path, doc, _auth in sorted(by_tag[tag], key=lambda r: (r[1], r[0])):
            first = doc.split(". ")[0][:140].rstrip(".")
            lines.append(f"- `{method} {path}`" + (f" — {first}" if first else ""))
        lines.append("")
    out = REPO / "docs" / "API.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({total} operations)")


if __name__ == "__main__":
    main()
