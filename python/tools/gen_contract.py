"""
Regenerate shared/contract/escalation-contract.json.

The escalation rules exist in three places because three languages cannot share
one implementation here: Kotlin (the shared module, authoritative), Python (the
server's copy) and Swift (the iOS app). test_parity.py pins Kotlin against
Python by parsing the source. It cannot reach Swift — that needs a Mac and an
Xcode toolchain.

This file is the third leg. It writes down, as data, everything a non-Kotlin
implementation has to agree with: the stage names, the terminal set, the
timings, the roster limits, and a full missed-morning timeline. The Swift test
target reads the same file, so an iOS developer who runs the tests on a Mac
finds out immediately if their copy has drifted.

Run it after changing a timing in config.py or a constant in CheckIn.kt:

    python/.venv/Scripts/python -m python.tools.gen_contract

Then run python/tests/test_contract.py, which is where the human-pinned
expectations live. If that test fails, the change was not propagated.
"""
import json
from pathlib import Path

from python import config
from python.models import (
    METHOD_IN_PERSON,
    METHOD_IVR,
    METHOD_PASSIVE,
    METHOD_TAPPED,
    STAGE_CALLED,
    STAGE_CHECKED_IN,
    STAGE_GUARDIANS_ALERTED,
    STAGE_HELPERS_ALERTED,
    STAGE_REMINDED,
    STAGE_RESOLVED,
    STAGE_WAITING,
    TERMINAL_STAGES,
)

OUTPUT = (
    Path(__file__).resolve().parents[2] / "shared" / "contract" / "escalation-contract.json"
)

# EscalationAction, mirrored from CheckIn.kt. Not defined in Python as constants
# yet, so they are written out here and the contract test pins them by name.
ACTION_NONE = "None"
ACTION_REMIND_USER = "RemindUser"
ACTION_PLACE_IVR_CALL = "PlaceIvrCall"
ACTION_ALERT_GUARDIANS = "AlertGuardians"
ACTION_ALERT_HELPERS = "AlertHelpers"
ACTION_NOTIFY_ALL_FINE = "NotifyAllFine"


def build() -> dict:
    # Every offset below is minutes past the moment the window opens.
    remind = config.REMIND_AFTER_S // 60
    closes = 180  # CheckInSettings.DEFAULT_WINDOW_MINUTES
    gap = config.IVR_RETRY_GAP_S // 60
    second_call = closes + gap
    guardians = second_call + gap
    helpers = guardians + config.HELPER_ESCALATION_S // 60

    return {
        "_comment": (
            "Generated by python/tools/gen_contract.py. Do not edit by hand. "
            "Regenerate, then run python/tests/test_contract.py and the Swift "
            "target's EscalationContractTests."
        ),
        "authority": "shared/feature-checkin/src/commonMain/kotlin/in/doosripari/feature/checkin/CheckIn.kt",
        "stages": [
            STAGE_WAITING,
            STAGE_REMINDED,
            STAGE_CALLED,
            STAGE_GUARDIANS_ALERTED,
            STAGE_HELPERS_ALERTED,
            STAGE_CHECKED_IN,
            STAGE_RESOLVED,
        ],
        "terminalStages": list(TERMINAL_STAGES),
        "actions": [
            ACTION_NONE,
            ACTION_REMIND_USER,
            ACTION_PLACE_IVR_CALL,
            ACTION_ALERT_GUARDIANS,
            ACTION_ALERT_HELPERS,
            ACTION_NOTIFY_ALL_FINE,
        ],
        "methods": [METHOD_TAPPED, METHOD_PASSIVE, METHOD_IVR, METHOD_IN_PERSON],
        "window": {
            "defaultStartLocal": "09:00",
            "defaultMinutes": closes,
            "maxMinutes": 1440,
        },
        "timingsSeconds": {
            "remindAfter": config.REMIND_AFTER_S,
            "ivrRetryGap": config.IVR_RETRY_GAP_S,
            "ivrAttempts": config.IVR_ATTEMPTS,
            "helperEscalationAfter": config.HELPER_ESCALATION_S,
        },
        "roster": {
            "maxGuardians": config.MAX_GUARDIANS,
            "maxHelpers": config.MAX_HELPERS,
            "pauseMinDays": config.PAUSE_MIN_DAYS,
            "pauseMaxDays": config.PAUSE_MAX_DAYS,
        },
        # One morning, fully missed. Offsets are minutes past window open.
        "missedMorning": [
            {"atMinutes": 0, "stage": STAGE_WAITING, "action": ACTION_NONE,
             "note": "Window opens."},
            {"atMinutes": remind, "stage": STAGE_REMINDED, "action": ACTION_REMIND_USER,
             "note": "An hour with no check-in. Push only; nobody is telephoned yet."},
            {"atMinutes": closes, "stage": STAGE_CALLED, "action": ACTION_PLACE_IVR_CALL,
             "note": "Window closed. First automated call."},
            {"atMinutes": second_call, "stage": STAGE_CALLED, "action": ACTION_PLACE_IVR_CALL,
             "note": "Second automated call, the gap after the first."},
            {"atMinutes": guardians, "stage": STAGE_GUARDIANS_ALERTED,
             "action": ACTION_ALERT_GUARDIANS,
             "note": "Both calls unanswered. Family told — not before this, "
                     "not one second earlier."},
            {"atMinutes": helpers, "stage": STAGE_HELPERS_ALERTED,
             "action": ACTION_ALERT_HELPERS,
             "note": "An hour with no acknowledgement. Nearby helpers told."},
        ],
        "terminalNote": (
            "A check-in at any minute, including one that lands after guardians "
            "were told, ends escalation and sends NotifyAllFine immediately."
        ),
    }


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(build(), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
