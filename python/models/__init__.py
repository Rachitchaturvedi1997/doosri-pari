# Doosri Pari — schema, re-exported.
#
# The tables are split across nine files by plan section rather than kept in
# one 1500-line module, and everything is re-exported from here. Callers import
# from `python.models` and never learn which file a table lives in:
#
#     from python.models import Base, User, CheckIn
#
# This is the same import path the old single `models.py` used, so routes,
# jobs, tests and the Alembic env all keep working untouched.
#
# Two rules this module enforces by being the only place tables are declared:
#
#   1. Alembic autogenerate diffs `Base.metadata` against the database, and
#      `test_migrations.py` fails on any difference. Every table must therefore
#      be imported here or it will not be in `Base.metadata` and will silently
#      never get a migration.
#   2. Two mappers for one `__tablename__` is a startup error, not a warning.
#      A duplicate is caught at import, which is the cheapest place to catch it.
# =============================================================================
